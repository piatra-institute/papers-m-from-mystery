# (name, dim SU(3), dim SU(2), hypercharge Y, Dynkin index T3, T2)
# All fields left-handed Weyl; T(fund) = 1/2 per factor, 0 for singlets.
GENERATION = [
    ("qL",    3, 2, F(1, 6)),
    ("dbarR", 3, 1, F(1, 3)),      # conjugate triplet; index equals fund
    ("ubarR", 3, 1, F(-2, 3)),
    ("lL",    1, 2, F(-1, 2)),
    ("ebarR", 1, 1, F(1, 1)),
    ("nbarR", 1, 1, F(0, 1)),
]


def _anomaly_sums(multiplets):
    su3 = sum(F(1, 2) * d2 * y for (_, d3, d2, y) in multiplets if d3 == 3)
    su2 = sum(F(1, 2) * d3 * y for (_, d3, d2, y) in multiplets if d2 == 2)
    y3 = sum(d3 * d2 * y ** 3 for (_, d3, d2, y) in multiplets)
    grav = sum(d3 * d2 * y for (_, d3, d2, y) in multiplets)
    doublets = sum(d3 for (_, d3, d2, y) in multiplets if d2 == 2)
    return {
        "su3_su3_u1": su3,
        "su2_su2_u1": su2,
        "u1_cubed": y3,
        "grav_grav_u1": grav,
        "witten_doublets": doublets,
    }


def run_generation() -> dict:
    total_states = sum(d3 * d2 for (_, d3, d2, _) in GENERATION)
    sums = _anomaly_sums(GENERATION)
    ok = (sums["su3_su3_u1"] == 0 and sums["su2_su2_u1"] == 0
          and sums["u1_cubed"] == 0 and sums["grav_grav_u1"] == 0
          and sums["witten_doublets"] % 2 == 0)
    deletions = {}
    for i, (name, *_rest) in enumerate(GENERATION):
        rest = GENERATION[:i] + GENERATION[i + 1:]
        s = _anomaly_sums(rest)
        broken = [k for k in ("su3_su3_u1", "su2_su2_u1", "u1_cubed",
                              "grav_grav_u1") if s[k] != 0]
        if s["witten_doublets"] % 2 == 1:
            broken.append("witten_parity")
        deletions[name] = broken
    return {
        "multiplets": [{"name": n, "su3": d3, "su2": d2,
                        "hypercharge": str(y), "states": d3 * d2}
                       for (n, d3, d2, y) in GENERATION],
        "total_weyl_states": total_states,
        "anomaly_sums": {k: str(v) for k, v in sums.items()},
        "all_conditions_hold": ok,
        "deletion_breaks": deletions,
        "deletions_that_break_nothing": [k for k, v in deletions.items()
                                         if not v],
    }


# ----------------------------------------------------------------------
# mechanism 2: the global-form atlas
# ----------------------------------------------------------------------
# Center classes live in Z3 x Z2 x Z6: color triality t, weak duality d,
# and hypercharge class y = 6Y mod 6. The Z6 generator acts on a class by
# the phase (t/3 + d/2 + y/6) mod 1; Gamma is generated by powers of the
# order-6 element z = (1, 1, 1) acting through that phase.

def _cls(d3, d2, y):
    t = {1: 0, 3: 1}[d3] if d3 in (1, 3) else None
    # conjugate triplets carry triality 2; encode via the sign of Y usage:
    return t, {1: 0, 2: 1}[d2], int(6 * y) % 6


MATTER_CLASSES = {
    "qL":    (1, 1, 1),
    "dbarR": (2, 0, 2),
    "ubarR": (2, 0, 2),
    "lL":    (0, 1, 3),
    "ebarR": (0, 0, 0),
    "nbarR": (0, 0, 0),
}

GAMMAS = {"1": 6, "Z2": 3, "Z3": 2, "Z6": 1}   # name -> generator power k
                                               # Gamma = <z^k>, |Gamma| = 6/k... see below


def _phase(cls, power):
    """Phase (in units of 1/6) with which z^power acts on a class."""
    t, d, y = cls
    # z = (omega, -1, e^{i pi /3}) acting on (t, d, y): phase = 2t/6? Use
    # sixths: t contributes 2t, d contributes 3d, y contributes y, mod 6.
    return (power * (2 * t + 3 * d + y)) % 6


def run_global_forms() -> dict:
    # the screening subgroup generated by matter classes in Z3 x Z2 x Z6
    def add(a, b):
        return ((a[0] + b[0]) % 3, (a[1] + b[1]) % 2, (a[2] + b[2]) % 6)

    screen = {(0, 0, 0)}
    frontier = list(MATTER_CLASSES.values())
    while frontier:
        nxt = []
        for s in list(screen):
            for m in frontier:
                x = add(s, m)
                if x not in screen:
                    screen.add(x)
                    nxt.append(x)
        frontier = nxt
    all_classes = [(t, d, y) for t in range(3) for d in range(2)
                   for y in range(6)]
    n_classes = len(all_classes)

    forms = {}
    gamma_orders = {"1": 1, "Z2": 2, "Z3": 3, "Z6": 6}
    for name, order in gamma_orders.items():
        k = 6 // order                      # Gamma = <z^k>
        # Wilson classes allowed in G/Gamma: trivial phase under z^k
        wilson = [c for c in all_classes if _phase(c, k) == 0] \
            if order > 1 else all_classes
        # matter admissibility
        matter_ok = all(_phase(MATTER_CLASSES[m], k) == 0
                        for m in MATTER_CLASSES) if order > 1 else True
        # electric one-form classes: allowed Wilson classes modulo screening
        wilson_set = set(wilson)
        # count cosets of the screening subgroup inside the allowed classes
        seen, cosets = set(), 0
        for c in wilson:
            if c in seen:
                continue
            cosets += 1
            for s in screen:
                seen.add(add(c, s))
        forms[name] = {
            "gamma_order": order,
            "n_wilson_classes": len(wilson),
            "electric_one_form_order": cosets,
            "magnetic_one_form_order": order,
            "product": cosets * order,
            "matter_admissible": matter_ok,
        }

    # Dirac pairing on the Z6 electric x Z6 magnetic torus: a pair
    # (e, m') is mutually local with (e', m) iff (e m' - e' m) = 0 mod 6.
    # For each Gamma the allowed set is E x M with E = <gamma_order'>?
    # Concretely: E_k = multiples of k in Z6 has order 6/k, M_k = subgroup
    # of order k; check pairing integral within each allowed lattice.
    pairing_ok = {}
    lattices = {}
    for name, order in gamma_orders.items():
        k = 6 // order
        E = [e for e in range(6) if e % (order if order < 6 else 6) == 0] \
            if order > 1 else list(range(6))
        E = sorted({(e * 1) % 6 for e in range(0, 6, max(1, order))})
        M = sorted({(m * k) % 6 for m in range(order)})
        ok = all((e * m) % 6 == 0 for e in E for m in M)
        pairing_ok[name] = ok
        lattices[name] = {"electric": E, "magnetic": M}
    distinct = len({(tuple(v["electric"]), tuple(v["magnetic"]))
                    for v in lattices.values()})
    return {
        "n_center_classes": n_classes,
        "screening_subgroup_order": len(screen),
        "matter_classes": {k: list(v) for k, v in MATTER_CLASSES.items()},
        "forms": forms,
        "lattices": lattices,
        "dirac_pairing_integral": pairing_ok,
        "n_distinct_lattices": distinct,
    }



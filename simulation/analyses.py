def _su3_decompose(weights):
    """Decompose a weight multiset (dict weight -> multiplicity) into
    irreducibles of su(3) by iterative highest-weight peeling."""
    # weights are (a, b) in the Dynkin basis; dominance order by peeling
    from collections import Counter
    W = Counter(weights)
    content = Counter()
    while any(v > 0 for v in W.values()):
        # find the highest weight present: maximize (a+b, a) lexicographic
        hw = max((w for w, m in W.items() if m > 0),
                 key=lambda w: (w[0] + w[1], w[0]))
        mult = W[hw]
        content[hw] += mult
        for w, m in _irrep_weights_su3(hw).items():
            W[w] -= mult * m
    return dict(content)


def _irrep_weights_su3(hw):
    """Weight multiplicities of the su(3) irrep with highest weight
    (a, b), via Freudenthal on a small grid."""
    a, b = hw
    # generate candidate weights: hw - n1*alpha1 - n2*alpha2
    # in Dynkin basis: alpha1 = (2, -1), alpha2 = (-1, 2)
    from collections import Counter
    cand = {}
    for n1 in range(0, a + b + 3):
        for n2 in range(0, a + b + 3):
            w = (a - 2 * n1 + n2, b + n1 - 2 * n2)
            cand[(n1, n2)] = w
    # Freudenthal recursion by level
    mult = {(0, 0): 1}
    rho = (1, 1)

    def ip(u, v):
        # inner product in Dynkin basis via the su(3) quadratic form
        # (u, v) = u^T F v with F = (1/3) [[2,1],[1,2]]
        return F(2 * u[0] * v[0] + u[0] * v[1] + u[1] * v[0]
                 + 2 * u[1] * v[1], 3)

    levels = sorted(cand, key=lambda n: n[0] + n[1])
    hw_v = (a, b)
    for n in levels:
        if n == (0, 0):
            continue
        w = cand[n]
        num = F(0)
        for alpha, step in ((( 2, -1), (1, 0)), ((-1, 2), (0, 1)),
                            (( 1,  1), (1, 1))):
            k = 1
            while True:
                nn = (n[0] - k * step[0], n[1] - k * step[1])
                if nn[0] < 0 or nn[1] < 0 or nn not in cand:
                    break
                m_up = mult.get(nn, 0)
                if m_up:
                    wk = (w[0] + k * alpha[0], w[1] + k * alpha[1])
                    num += m_up * ip(wk, alpha)
                k += 1
        denom = (ip((hw_v[0] + rho[0], hw_v[1] + rho[1]),
                    (hw_v[0] + rho[0], hw_v[1] + rho[1]))
                 - ip((w[0] + rho[0], w[1] + rho[1]),
                      (w[0] + rho[0], w[1] + rho[1])))
        m = 2 * num / denom if denom != 0 else F(0)
        if m > 0:
            mult[n] = int(m)
    out = Counter()
    for n, m in mult.items():
        out[cand[n]] += m
    return dict(out)


def _tensor_su3(hw1, hw2):
    from collections import Counter
    w1 = _irrep_weights_su3(hw1)
    w2 = _irrep_weights_su3(hw2)
    prod = Counter()
    for a, ma in w1.items():
        for b, mb in w2.items():
            prod[(a[0] + b[0], a[1] + b[1])] += ma * mb
    return _su3_decompose(prod)


def run_fusion() -> dict:
    F3 = (1, 0)          # fundamental 3
    # 3 x 3
    t33 = _tensor_su3(F3, F3)
    # (3 x 3) x 3
    from collections import Counter
    t333 = Counter()
    for hw, m in t33.items():
        for hw2, m2 in _tensor_su3(hw, F3).items():
            t333[hw2] += m * m2
    dim = lambda hw: (hw[0] + 1) * (hw[1] + 1) * (hw[0] + hw[1] + 2) // 2
    name = {(0, 0): "1", (1, 0): "3", (0, 1): "3bar", (2, 0): "6",
            (1, 1): "8", (3, 0): "10", (0, 2): "6bar"}
    singlet_in_33 = t33.get((0, 0), 0)
    singlet_in_333 = t333.get((0, 0), 0)
    dim_check_333 = sum(dim(h) * m for h, m in t333.items())

    # SU(2) fusion ring: irreps labeled by dimension n; n x m = |n-m|+1..n+m-1
    def su2_tensor(n, m):
        return list(range(abs(n - m) + 1, n + m, 2))

    max_dim = 8
    prime = {}
    summand_of_smaller = {}
    for n in range(2, max_dim + 1):
        # tensor-prime: no factorization n = a (x) b as a single irrep
        is_prime = True
        for a in range(2, n):
            for b in range(2, n):
                if su2_tensor(a, b) == [n]:
                    is_prime = False
        prime[n] = is_prime
        # bound-state realization: n as a summand of 2 (x) (n-1)
        summand_of_smaller[n] = n in su2_tensor(2, n - 1)

    return {
        "su3_3x3": {name.get(h, str(h)): m for h, m in sorted(t33.items())},
        "su3_3x3x3": {name.get(h, str(h)): m for h, m in sorted(t333.items())},
        "singlet_in_3x3": singlet_in_33,
        "singlet_in_3x3x3": singlet_in_333,
        "dim_check_3x3x3": dim_check_333,
        "su2_max_dim": max_dim,
        "su2_all_irreps_tensor_prime": all(prime.values()),
        "su2_all_composite_as_summand": all(summand_of_smaller.values()),
    }



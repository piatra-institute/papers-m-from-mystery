BOX = 40


def run_sl2z() -> dict:
    n_total = 0
    n_prim = 0
    orbit_iff_coprime = True
    decomposable = 0
    for p in range(-BOX, BOX + 1):
        for q in range(-BOX, BOX + 1):
            if (p, q) == (0, 0):
                continue
            n_total += 1
            g = math.gcd(p, q)
            if g == 1:
                n_prim += 1
                # constructive Bezout witness: p*s - q*r = 1
                r, s = _bezout(p, q)
                if p * s - q * r != 1:
                    orbit_iff_coprime = False
                # the no-go: a two-constituent decomposition with both
                # parts nonzero
                a, b = (1, 0) if (p, q) != (1, 0) else (2, 0)
                c, d = p - a, q - b
                if (a, b) != (0, 0) and (c, d) != (0, 0):
                    decomposable += 1
    density = n_prim / n_total
    return {
        "box": BOX,
        "n_vectors": n_total,
        "n_primitive": n_prim,
        "primitive_density": round(density, 6),
        "six_over_pi_squared": round(6 / math.pi ** 2, 6),
        "density_gap_pct": round(100 * abs(density - 6 / math.pi ** 2)
                                 / (6 / math.pi ** 2), 3),
        "orbit_iff_coprime_verified": orbit_iff_coprime,
        "primitive_all_decomposable": decomposable == n_prim,
    }


def _bezout(p, q):
    """Return (r, s) with p*s - q*r = 1 for coprime (p, q)."""
    # extended euclid on (p, q): find x, y with p*x + q*y = 1
    old_r, r = p, q
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r != 0:
        quot = old_r // r
        old_r, r = r, old_r - quot * r
        old_s, s = s, old_s - quot * s
        old_t, t = t, old_t - quot * t
    # p*old_s + q*old_t = old_r = +-gcd = +-1
    sign = old_r  # +1 or -1
    x, y = old_s * sign, old_t * sign
    # want p*s' - q*r' = 1: take s' = x, r' = -y
    return -y, x



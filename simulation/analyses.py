"""Exact arithmetic for the reconstruction programme.

Four mechanisms, all deterministic and exact (integer and rational
arithmetic throughout; no floats except in reported densities):

1. The one-generation ledger. The 16 left-handed Weyl states of one
   Standard Model generation, their hypercharges as exact fractions, the
   five consistency sums (two mixed gauge anomalies, the cubic
   hypercharge anomaly, the mixed gravitational anomaly, and the Witten
   SU(2) doublet parity), and the deletion-rigidity table: which sums
   break when each multiplet is removed. The right-handed neutrino is the
   one multiplet whose deletion breaks nothing.

2. The global-form atlas. The center-class group Z3 x Z2 x Z6, the
   screening subgroup generated by the six matter classes, and, for each
   subgroup Gamma of Z6, the surviving electric line classes, the
   magnetic classes, the integrality of the Dirac pairing, and the
   admissibility of all six matter multiplets under all four global
   forms: identical perturbation theory, four distinct theories.

3. The SL(2,Z) orbit. Over a charge box, membership in the orbit of the
   unit electric charge coincides with coprimality, witnessed by explicit
   Bezout matrices of determinant 1; the coprime density approaches
   6/pi^2; and every primitive vector decomposes into two nonzero
   constituents, which is the no-go: primitive labels never establish
   indivisible carriers.

4. The fusion counterexamples. In SU(3), the singlet appears exactly once
   in 3 x 3 x 3 and never in 3 x 3 (the proton toy: simple and
   composite). In the SU(2) fusion ring, every irreducible is
   tensor-prime while every spin above one half is a summand of a product
   of smaller spins: the bound-state relation is a summand, never a
   factor, so tensor-primality detects nothing.

Invariants fail the run.
"""
from __future__ import annotations


def _checks(gen, glob, sl2, fus) -> dict:
    c = {}
    c["sixteen_weyl_states"] = gen["total_weyl_states"] == 16
    c["all_five_conditions_hold"] = gen["all_conditions_hold"]
    c["five_deletions_break"] = sum(
        1 for v in gen["deletion_breaks"].values() if v) == 5
    c["only_nu_breaks_nothing"] = gen["deletions_that_break_nothing"] == ["nbarR"]
    c["screening_subgroup_is_z6"] = glob["screening_subgroup_order"] == 6
    c["matter_admissible_under_all_forms"] = all(
        v["matter_admissible"] for v in glob["forms"].values())
    c["electric_magnetic_orders_multiply_to_six"] = all(
        v["product"] == 6 for v in glob["forms"].values())
    c["dirac_pairing_integral"] = all(glob["dirac_pairing_integral"].values())
    c["four_distinct_lattices"] = glob["n_distinct_lattices"] == 4
    c["orbit_iff_coprime"] = sl2["orbit_iff_coprime_verified"]
    c["primitive_density_near_6_over_pi2"] = sl2["density_gap_pct"] < 2.0
    c["every_primitive_decomposes"] = sl2["primitive_all_decomposable"]
    c["singlet_absent_in_3x3"] = fus["singlet_in_3x3"] == 0
    c["singlet_once_in_3x3x3"] = fus["singlet_in_3x3x3"] == 1
    c["dimension_check_27"] = fus["dim_check_3x3x3"] == 27
    c["su2_tensor_primality_universal"] = fus["su2_all_irreps_tensor_prime"]
    c["su2_bound_states_are_summands"] = fus["su2_all_composite_as_summand"]
    return c


def run() -> dict:
    gen = run_generation()
    glob = run_global_forms()
    sl2 = run_sl2z()
    fus = run_fusion()
    checks = _checks(gen, glob, sl2, fus)
    failed = [k for k, v in checks.items() if not v]
    if failed:
        raise SystemExit(f"INVARIANT FAILURES: {failed}")
    return {
        "generation": gen,
        "global_forms": glob,
        "sl2z": sl2,
        "fusion": fus,
        "constants": {"BOX": BOX, "SEED": SEED},
        "checks": checks,
    }
